"""Prepares the two benchmark sketches (INT8 and FP32) for the Arduino IDE.

Writes bench_samples.h (the first N raw Min-Max rows of data/test_device.csv, used by the BENCH command) and copies
bench_common.h, bench_samples.h and the model header of each build into its sketch folder, so that every sketch folder
is self-contained.

    python device_bench/make_bench_samples.py            (run it from m5stack_ids_eval/)
"""
import argparse
import shutil
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def c_float(v):
    """C++ float literal: '0f' or '1f' are not valid, so integers get a '.0' (0.0f, 1.0f)."""
    s = f'{float(v):.9g}'
    if '.' not in s and 'e' not in s:
        s += '.0'
    return s + 'f'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--data', default=str(ROOT / 'data' / 'test_device.csv'), help='raw Min-Max rows, 61 features + label, no header')
    parser.add_argument('--n', type=int, default=100, help='samples stored in flash for the BENCH command')
    args = parser.parse_args()

    df = pd.read_csv(args.data, header=None, nrows=args.n)
    x = df.iloc[:, :-1].values.astype(np.float32)
    y = df.iloc[:, -1].values.astype(int)
    n, dim = x.shape

    lines = ['// Generated by make_bench_samples.py: raw Min-Max rows of the test set, rescaled on the board by the BENCH command.',
             '#pragma once', f'#define BENCH_N {n}', f'#define BENCH_DIM {dim}',
             f'static const float bench_samples[BENCH_N][BENCH_DIM] = {{']
    for row in x:
        lines.append('  {' + ', '.join(c_float(v) for v in row) + '},')
    lines.append('};')
    lines.append(f'static const int8_t bench_labels[BENCH_N] = {{{", ".join(str(v) for v in y)}}};')
    header = HERE / 'bench_samples.h'
    header.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{header.name}: {n} samples x {dim} features ({n * dim * 4} bytes of flash)')

    builds = {
        'arduino_m5_ids_int8_bench': ROOT / 'arduino_m5_ids_int8' / 'exp6_qat_int8_model.h',
        'arduino_m5_ids_fp32_bench': ROOT / 'arduino_m5_ids_normal_exp6' / 'exp6_normal_model.h',
    }
    for folder, model_header in builds.items():
        target = HERE / folder
        for src in (HERE / 'bench_common.h', header, model_header):
            shutil.copy(src, target / src.name)
        print(f'{folder}: copied bench_common.h, bench_samples.h, {model_header.name}')


if __name__ == '__main__':
    main()
